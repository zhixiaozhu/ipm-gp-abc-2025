    @property
    def build_new_m_sur(self):
        if self.target != 'm_sur':
            warnings.warn("Building new m_sur, but the target is not m_sur")

        f64 = gpflow.utilities.to_default_float
        l = gpflow.likelihoods.Bernoulli()
        kernel = gpflow.kernels.RBF(lengthscales=np.array([1,1]))

        m_sur_new = gpflow.models.GPMC(data=(self.X_sur, self.Y_sur), kernel=kernel, likelihood=l)
        m_sur_new.kernel.lengthscales.prior = tfd.InverseGamma(f64(0.001),f64(0.001))
        m_sur_new.kernel.variance.prior = tfd.InverseGamma(f64(0.001),f64(0.001))

        return m_sur_new


