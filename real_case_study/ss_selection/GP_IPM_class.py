class GP_IPM:
    def __init__(self, popu_data, GPmodel_true, NB=None):
        # popu_data is the observed dataset 
        # GPmodel_true is the true model generate the simulated population behind.
        # NB is a boolean to indicate whether Negative Binomial model is used for flowring stalks.
        # size_t and age_t are the individual state at time t (without considering newborns at t+1)
        self.popu_data = popu_data
        self.GPmodel_true = GPmodel_true
        self.NB = NB
        self.size_t = self.size_t_compu
        self.age_t = self.age_t_compu
    
    @property
    def age_t_compu(self):
        return self.popu_data.loc[self.popu_data['age'].notna(), 'age']
    
    @property
    def size_t_compu(self):
        return self.popu_data.loc[self.popu_data['size'].notna(), 'size']



