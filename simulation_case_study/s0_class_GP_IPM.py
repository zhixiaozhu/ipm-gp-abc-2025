    @property
    def build_new_m_sur(self):
        if self.target != 'm_sur':
            warnings.warn("Building new m_sur, but the target is not m_sur")

        l = gpflow.likelihoods.Bernoulli()
        kernel = gpflow.kernels.RBF()

        m_sur_new = gpflow.models.GPMC(data=(self.X_sur, self.Y_sur), kernel=kernel, likelihood=l)

        if self.truedata_style == 'glm':
            m_sur_new.kernel.variance.prior = tfd.HalfNormal(scale=f64(50.))
            m_sur_new.kernel.lengthscales.prior = tfd.HalfNormal(scale=f64(50.))
        elif self.truedata_style == 'gp':
            m_sur_new.kernel.variance.prior = tfd.HalfNormal(scale=f64(50.))
            m_sur_new.kernel.lengthscales.prior = tfd.HalfNormal(scale=f64(50.))
        else:
           assert False, '\n truedata_style should be glm or gp' 
 

        return m_sur_new


