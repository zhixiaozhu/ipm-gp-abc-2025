class GP_IPM:
    def __init__(self, popu_data, GPmodel_true, grw_setting, truedata_style):
        # popu_data is the observed dataset 
        # GPmodel_true is the true model generate the simulated population behind. (Here, is not exactly 
        #               the true model but the models for the calculated mle from the simulated dataset).
        self.popu_data = popu_data
        self.GPmodel_true = GPmodel_true
        self.grw_setting = grw_setting
        self.truedata_style = truedata_style
        self.size_t = self.size_t_compu
        self.age_t = self.age_t_compu
    
    @property
    def age_t_compu(self):
        return self.popu_data.loc[self.popu_data['age'].notna(), 'age']
    @property
    def size_t_compu(self):
        return self.popu_data.loc[self.popu_data['size'].notna(), 'size']



